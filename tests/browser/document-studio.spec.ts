import { test, expect } from '@playwright/test';
import { createProduction, signInToPlans } from '../helpers/plans.js';
import { revealEditorCommand } from '../helpers/editorMenus.js';
import { placeWallAt } from '../helpers/inspector.js';

test('layout pages, frame positions, one-gesture undo and page order survive draft reload and PDF preparation', async ({ page }) => {
  test.setTimeout(90_000);
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1600, height: 1000 });
  await signInToPlans(page);
  await createProduction(page, { productionName: 'RoboGirl · Aufbau', venueName: 'Probebühne', sceneName: 'Erster Akt' });
  await placeWallAt(page, 2500, 3000);
  await expect(page.locator('.save-status')).toHaveText('Gespeichert');
  await revealEditorCommand(page, 'PDF gestalten'); await page.getByRole('button', { name: 'PDF gestalten' }).click();
  const studio = page.getByRole('dialog', { name: 'Dokument erstellen' });
  await expect(studio.getByTestId('document-sheet')).toBeVisible();
  const originalPages = await studio.locator('.studio-page-card').count();
  await studio.getByRole('button', { name: 'Layouts', exact: true }).click();
  await studio.getByRole('button', { name: /Plan und Hinweise/ }).click();
  await expect(studio.locator('.studio-page-card')).toHaveCount(originalPages + 1);
  await studio.getByRole('button', { name: 'Grundriss auswählen', exact: true }).click();
  const width = studio.getByLabel('Rahmen Breite (mm)', { exact: true });
  await width.fill('120');
  await expect(width).toHaveValue('120');
  const x = studio.getByLabel('Rahmen X (mm)', { exact: true });
  const beforeX = Number(await x.inputValue());
  const move = studio.getByRole('button', { name: 'Grundriss auswählen', exact: true });
  await move.focus(); await page.keyboard.press('ArrowRight');
  await expect(x).toHaveValue(String(beforeX + 1));
  await studio.getByRole('button', { name: 'Rückgängig', exact: true }).click();
  await expect(x).toHaveValue(String(beforeX));
  await studio.getByRole('button', { name: 'Entwurf speichern', exact: true }).click();
  await expect(studio.locator('.studio-save-state')).toHaveText('Gespeichert');
  const draftWrites: string[] = [];
  page.on('request', request => { if (request.method() === 'PUT' && request.url().endsWith('/document-draft')) draftWrites.push(request.url()); });
  const rect = await move.boundingBox(); if (!rect) throw new Error('Drawing frame missing');
  await page.mouse.move(rect.x + rect.width * .5, rect.y + rect.height * .5);
  await page.mouse.down(); await page.mouse.move(rect.x + rect.width * .5 + 30, rect.y + rect.height * .5 + 12, { steps: 6 });
  await page.waitForTimeout(1500); // Hold beyond autosave's quiet period: a gesture preview must not be persisted.
  expect(draftWrites).toHaveLength(0);
  await page.mouse.up();
  await expect(studio.locator('.studio-save-state')).toHaveText('Gespeichert');
  expect(draftWrites).toHaveLength(1);
  expect(Number(await x.inputValue())).toBeGreaterThan(beforeX);
  await expect(studio.getByLabel('Rahmenmaßstab')).toHaveValue('50');
  await studio.getByRole('button', { name: 'Rückgängig', exact: true }).click();
  await expect(x).toHaveValue(String(beforeX));
  await studio.getByRole('button', { name: 'Text und Hinweise auswählen', exact: true }).click();
  await studio.getByLabel('Text', { exact: true }).fill('Aufbau ab 09:00 Uhr. Bitte zuerst die Rückwand stellen.');
  await studio.getByRole('button', { name: 'Duplizieren', exact: true }).click();
  await expect(studio.locator('.studio-page-card')).toHaveCount(originalPages + 2);
  await studio.getByRole('button', { name: 'Seite nach oben', exact: true }).click();
  await studio.getByLabel('Blattname', { exact: true }).fill('Aufbau und Absprachen');
  await studio.getByRole('button', { name: 'Entwurf speichern', exact: true }).click();
  await expect(studio.locator('.studio-save-state')).toHaveText('Gespeichert');
  await page.screenshot({ path: 'test-results/document-studio-desktop.png' });
  await studio.getByRole('button', { name: 'Druckvorschau', exact: true }).click();
  await expect(studio.getByTitle('PDF-Vorschau')).toBeVisible({ timeout: 30_000 });
  await expect(studio.getByRole('button', { name: 'PDF herunterladen', exact: true })).toBeEnabled();
  await studio.getByRole('button', { name: 'Zurück zum Editor' }).click();
  await revealEditorCommand(page, 'PDF gestalten'); await page.getByRole('button', { name: 'PDF gestalten' }).click();
  await expect(studio.getByRole('button', { name: /Seite \d+: Aufbau und Absprachen/ })).toBeVisible();
  await studio.getByRole('button', { name: /Seite \d+: Aufbau und Absprachen/ }).click();
  await expect(studio.getByLabel('Blattname', { exact: true })).toHaveValue('Aufbau und Absprachen');
  expect(errors).toEqual([]);
});

test('a captured 3D frame is embedded in the PDF and cancelling a preset change keeps the studio draft', async ({ page }) => {
  test.setTimeout(120_000);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await signInToPlans(page);
  await createProduction(page, { productionName: 'Raum und Plan', venueName: 'Studio', sceneName: 'Bühnenprobe' });
  await placeWallAt(page, 2500, 3000);
  await expect(page.locator('.save-status')).toHaveText('Gespeichert');
  await revealEditorCommand(page, 'PDF gestalten'); await page.getByRole('button', { name: 'PDF gestalten' }).click();
  const studio = page.getByRole('dialog', { name: 'Dokument erstellen' });
  await studio.getByRole('button', { name: 'Layouts', exact: true }).click();
  await studio.getByRole('button', { name: /Plan und Raumsicht/ }).click();
  await studio.getByRole('button', { name: 'Raumsicht auswählen', exact: true }).click();
  await studio.getByRole('button', { name: 'Raumsicht aufnehmen', exact: true }).click();
  const capture = studio.getByRole('region', { name: 'Raumsicht aufnehmen', exact: true });
  await expect(capture.locator('canvas')).toBeVisible({ timeout: 30_000 });
  await expect(capture.getByRole('button', { name: 'Ansicht übernehmen' })).toBeEnabled({ timeout: 30_000 });
  await capture.getByRole('button', { name: 'Ansicht übernehmen' }).click();
  await expect(capture).toBeHidden({ timeout: 30_000 });
  await expect(studio.getByTestId('document-sheet').locator('image')).toHaveCount(1);
  await expect(studio.getByTestId('document-sheet').locator('image')).toHaveAttribute('href', /^data:image\/png/);
  await studio.getByRole('button', { name: 'Entwurf speichern', exact: true }).click();
  await expect(studio.locator('.studio-save-state')).toHaveText('Gespeichert');
  await page.screenshot({ path: 'test-results/document-studio-3d.png' });
  await studio.getByRole('button', { name: 'Dokument', exact: true }).click();
  const count = await studio.locator('.studio-page-card').count();
  await studio.getByRole('button', { name: /^Regie \/ Probe/ }).click();
  const confirm = page.getByRole('dialog', { name: 'Seiten neu aufbauen?' });
  await expect(confirm).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(confirm).toBeHidden();
  await expect(studio).toBeVisible();
  await expect(studio.locator('.studio-page-card')).toHaveCount(count);
  await studio.getByRole('button', { name: 'Druckvorschau', exact: true }).click();
  await expect(studio.getByTitle('PDF-Vorschau')).toBeVisible({ timeout: 30_000 });
  const source = await studio.getByTitle('PDF-Vorschau').getAttribute('src');
  const bytes = await page.evaluate(async url => Array.from(new Uint8Array(await (await fetch(url!)).arrayBuffer())), source);
  expect(Buffer.from(bytes).toString('latin1')).toMatch(/\/Subtype\s*\/Image/);
});
